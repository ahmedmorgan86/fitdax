import assert from 'node:assert/strict';
import {authInput,isGoogleUser} from './lib/auth-input.mjs';
for(const action of ['login','signup','reset','update-password','send','verify'])assert.throws(()=>authInput({action,email:'qa@example.invalid',password:'synthetic-password-long'}));
assert.throws(()=>authInput({action:'google',email:'qa@example.invalid'}));
assert.deepEqual(authInput({action:'google'}),{action:'google'});
assert.equal(isGoogleUser({email_confirmed_at:'2026-10-20',identities:[{provider:'email'}]}),false);
assert.equal(isGoogleUser({email_confirmed_at:null,identities:[{provider:'google'}]}),false);
assert.equal(isGoogleUser({email_confirmed_at:'2026-10-20',identities:[{provider:'google'}]}),true);
assert.equal(isGoogleUser({user_metadata:{provider:'google'}}),false);
console.log('PASS removed email/password/OTP actions rejected; only verified Google identity accepted; editable metadata ignored');
